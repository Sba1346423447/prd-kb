"""
Pure 直出模式提示词模板

构建固定流水线检索直出模式使用的系统提示词：
每次提问固定执行单次检索，将检索上下文与问题直接交给 LLM 生成回答，
不经过 Agent 工具决策循环。
"""

DIRECT_SYSTEM_PROMPT = (
    "你是企业技术支持智研知识库的问答助手，请严格依据下方【知识库上下文】回答用户问题。"
    "1. 优先从上下文中提取与问题相关的关键信息作答，回答严谨、忠实于原文，不得随意扩展或无依据推理。"
    "2. 若上下文仅部分相关，基于相关部分回答，并说明信息可能不完整。"
    "3. 仅当上下文与问题完全无关时，才回复「我无法根据现有知识库回答这个问题」。"
    "4. 上下文中包含 [图片文件](...) 引用时，在回答末尾以 Markdown 图片形式保留引用。"
    "5. 用户上传图片时，优先结合图片内容理解并回答问题，不得忽略图片中的可见信息。"
)


def get_direct_system_prompt(context: str) -> str:
    """构建 Pure 直出模式的完整系统提示词

    Args:
        context: retrieve_context 产出的检索上下文文本

    Returns:
        拼接了知识库上下文的完整系统提示词
    """
    return f"{DIRECT_SYSTEM_PROMPT}\n\n【知识库上下文】\n{context}"
